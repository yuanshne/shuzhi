  // FNV-1a 字符串哈希，保证同一 id 永远得到同一颜色
  function hashId(id) {
    var h = 2166136261;
    var s = String(id);
    for (var i = 0; i < s.length; i += 1) {
      h ^= s.charCodeAt(i);
      h = Math.imul(h, 16777619) >>> 0;
    }
    return h >>> 0;
  }

